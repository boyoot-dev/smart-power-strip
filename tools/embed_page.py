# PlatformIO pre-build step: gzips web/index.html into include/web_page.h.
# The page is served gzipped, straight from flash. Sending it as a
# plain string made AsyncWebServer copy all 40 KB to the heap on every request; once TLS
# held its buffers that allocation failed and the browser got an empty page.
import gzip
import os

Import("env")  # noqa: F821  (provided by PlatformIO)

root = env["PROJECT_DIR"]  # noqa: F821
src = os.path.join(root, "web", "index.html")
dst = os.path.join(root, "include", "web_page.h")

with open(src, "rb") as f:
    gz = gzip.compress(f.read(), compresslevel=9, mtime=0)  # mtime=0: same bytes every build

rows = ",\n".join(", ".join("0x%02x" % b for b in gz[i:i + 20]) for i in range(0, len(gz), 20))
out = (
    "#pragma once\n\n"
    "// GENERATED by tools/embed_page.py from web/index.html - edit that file instead.\n"
    "#include <stddef.h>\n#include <stdint.h>\n\n"
    "static const uint8_t kIndexHtmlGz[] = {\n%s\n};\n"
    "static const size_t kIndexHtmlGzLen = sizeof(kIndexHtmlGz);\n" % rows
)
old = open(dst).read() if os.path.exists(dst) else None
if out != old:  # rewrite only on change, so unchanged builds stay incremental
    with open(dst, "w", newline="\n") as f:
        f.write(out)
print("embed_page: web/index.html -> %d bytes gzipped" % len(gz))
